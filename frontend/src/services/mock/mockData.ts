/** Konum bilgisine göre gerçekçi bir hava durumu üretir (mock) */
export const buildMockWeather = (
  latitude = 41.0082,
  longitude = 28.9784,
  city = 'İstanbul',
): WeatherSnapshot => {
  const month = new Date().getMonth();
  const hour = new Date().getHours();

  // Basit mevsimsel taban sıcaklık eğrisi
  const seasonalBase = [7, 8, 11, 16, 21, 26, 29, 29, 25, 19, 13, 9][month] ?? 18;
  const dayCurve = Math.sin(((hour - 6) / 24) * Math.PI * 2) * 3;
  const temperature = Math.round((seasonalBase + dayCurve) * 10) / 10;

  const conditions = ['clear', 'clouds', 'rain', 'clear', 'clouds'] as const;
  const condition = conditions[new Date().getDate() % conditions.length];

  const descriptions: Record<string, string> = {
    clear: 'Açık ve güneşli',
    clouds: 'Parçalı bulutlu',
    rain: 'Aralıklı yağmurlu',
  };

  const hourly = Array.from({ length: 12 }, (_, i) => {
    const h = (hour + i) % 24;
    return {
      time: new Date(Date.now() + i * 3600000).toISOString(),
      temperature:
        Math.round((seasonalBase + Math.sin(((h - 6) / 24) * Math.PI * 2) * 3) * 10) / 10,
      condition,
      precipitationProbability: condition === 'rain' ? 55 : 10,
    };
  });

  return {
    city,
    country: 'TR',
    coordinates: { latitude, longitude },
    temperature,
    feelsLike: Math.round((temperature - 1.2) * 10) / 10,
    minTemperature: Math.round((seasonalBase - 4) * 10) / 10,
    maxTemperature: Math.round((seasonalBase + 4) * 10) / 10,
    condition,
    description: descriptions[condition] ?? 'Parçalı bulutlu',
    humidity: condition === 'rain' ? 78 : 54,
    windSpeed: condition === 'rain' ? 28 : 14,
    precipitationProbability: condition === 'rain' ? 65 : 8,
    uvIndex: condition === 'clear' ? 6 : 3,
    hourly,
    fetchedAt: now(),
  };
};
